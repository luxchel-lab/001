<?php
/**
 * ЗАГЛУШКА · POST api/auth-request-code.php
 *
 * Приём: phone. Ответ: подтверждение, что код «отправлен».
 *
 * ── ЧТО ДОЛЖЕН ДЕЛАТЬ НАСТОЯЩИЙ БЭКЕНД ──────────────────────────────
 * 1. Привести номер к E.164 (+79991234567) и отвергнуть мусор.
 * 2. Ограничить частоту: не чаще одного кода в минуту на номер и
 *    не больше 5 в час на номер и на IP. Иначе через форму входа
 *    можно рассылать SMS за счёт магазина.
 * 3. Сгенерировать код (random_int, не rand), сохранить ХЕШ кода
 *    с секретом, а не сам код, и время жизни ~5 минут.
 * 4. Отправить SMS через шлюз оператора.
 * 5. НИКОГДА не возвращать код в ответе.
 *
 * Заглушка возвращает demoCode, чтобы демо можно было показать без
 * SMS-шлюза. В бою эту строку надо удалить.
 * ────────────────────────────────────────────────────────────────────
 */

require __DIR__ . '/_stub.php';
archi_ai_boot();

$phone = preg_replace('/\D+/', '', (string) archi_ai_input('phone'));

if (strlen($phone) < 10) {
    archi_ai_fail('phone_invalid', 'Проверьте номер телефона.', 422);
}

archi_ai_delay(0.6);   // имитация похода в SMS-шлюз

$state = &archi_ai_state();
$state['pendingPhone'] = $phone;

archi_ai_send(array(
    'ok'          => true,
    'demo'        => true,
    'phone'       => '+7' . substr($phone, -10, 3) . '***' . substr($phone, -4),
    'ttl'         => 300,
    'resendAfter' => 60,
    'demoCode'    => ARCHI_AI_DEMO_CODE,   // ← в бою удалить
));
